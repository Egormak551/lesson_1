score = int(input("Введите рейтинг товара от 0 до 10"))
match score:
    case 0|1|2:
        print("Плохой товар, не рекомендован ❌")
    case 3|4|5:
        print("Средний товар, на ваше усмотрение 🤔")
    case 6|7|8:
        print("Хороший товар, рекомендован ✅")
    case 9|10:
        print("Отличный товар, Можно уверенно брать 🌟")
    case _ :
        print("Введён неверный рейтинг")